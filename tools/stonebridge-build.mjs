#!/usr/bin/env node
// Bundles www/stonebridge/ into dist/stonebridge.js + dist/version.json.
//
// Why: HA serves /local/ with a long browser cache, and relative ES-module
// imports drop the ?v= query, so a multi-file module graph would go stale on
// phones. One bundled file, loaded by loader.js under ?v=<hash>, never does.
//
// Run after editing anything in www/stonebridge/:  node tools/stonebridge-build.mjs
// (`node --test tests/stonebridge/` fails if the bundle is out of date.)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "www", "stonebridge");

// Shared modules first (top level), then each card in its own block scope so
// file-local helpers (e.g. `cap`) cannot collide.
const SHARED = ["theme.js", "headlines.js", "base.js"];
const CARDS = ["cards/home.js", "cards/security.js", "cards/cameras.js", "cards/car.js", "cards/climate.js", "cards/lights.js"];

function strip(src) {
  return src
    .replace(/^import[\s\S]*?from\s+["'][^"']+["'];?\s*$/gm, "")
    .replace(/^export\s+(?=(const|function|class|let|async)\b)/gm, "");
}

export function build() {
  const parts = ["// GENERATED by tools/stonebridge-build.mjs — edit the sources, not this file."];
  for (const f of SHARED) parts.push(`// --- ${f}\n${strip(readFileSync(join(root, f), "utf8"))}`);
  for (const f of CARDS) parts.push(`// --- ${f}\n{\n${strip(readFileSync(join(root, f), "utf8"))}\n}`);
  const bundle = parts.join("\n");
  const version = createHash("sha256").update(bundle).digest("hex").slice(0, 12);
  return { bundle, versionJson: JSON.stringify({ version }) + "\n" };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { bundle, versionJson } = build();
  mkdirSync(join(root, "dist"), { recursive: true });
  writeFileSync(join(root, "dist", "stonebridge.js"), bundle);
  writeFileSync(join(root, "dist", "version.json"), versionJson);
  console.log(`stonebridge bundle ${JSON.parse(versionJson).version}`);
}
